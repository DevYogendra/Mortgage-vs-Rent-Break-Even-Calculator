import { test, expect } from '@playwright/test'

test('mortgage excludes extra charges and charge units preserve their amount', async ({ page }) => {
  await page.goto('/india')
  await page.getByLabel('Include waiting period', { exact: true }).check()
  await page.getByLabel('Home price', { exact: true }).fill('1')
  await page.getByLabel('Down payment', { exact: true }).fill('20')
  await page.getByLabel('Loan interest', { exact: true }).fill('0')
  await page.getByLabel('Upfront purchase charges', { exact: true }).fill('10')
  const mortgage = page.locator('.compact-mortgage')
  await expect(mortgage).toContainText('Mortgage principal₹80,00,000')
  await expect(mortgage).toContainText('Monthly mortgage payment₹33,333')
  await expect(mortgage).toContainText('Computed monthly savings₹2,083')
  await expect(mortgage).toContainText('Total upfront cash₹30,00,000')
  await expect(page.getByLabel('Liquid purchase funds', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Savings', { exact: true })).toHaveCount(0)
  const unit = page.getByLabel('Upfront purchase charges unit', { exact: true })
  await unit.selectOption('rupees')
  await expect(page.getByLabel('Upfront purchase charges', { exact: true })).toHaveValue('1000000')
  await page.getByLabel('Upfront purchase charges', { exact: true }).fill('2000000')
  await expect(mortgage).toContainText('Mortgage principal₹80,00,000')
  await expect(mortgage).toContainText('Monthly mortgage payment₹33,333')
  await expect(mortgage).toContainText('Total upfront cash₹40,00,000')
  await page.getByLabel('Home price', { exact: true }).fill('2')
  await expect(page.getByLabel('Upfront purchase charges', { exact: true })).toHaveValue('2000000')
  await unit.selectOption('percent')
  await expect(page.getByLabel('Upfront purchase charges', { exact: true })).toHaveValue('10')
  await unit.selectOption('rupees')
  await expect(page.getByLabel('Upfront purchase charges', { exact: true })).toHaveValue('2000000')
  await page.getByLabel('Upfront purchase charges', { exact: true }).fill('-1')
  await expect(page.getByLabel('Upfront purchase charges', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await expect(mortgage).toHaveCount(0)
  await page.getByLabel('Upfront purchase charges', { exact: true }).fill('2000000')
  await page.getByLabel('Down payment', { exact: true }).fill('201')
  await expect(page.getByLabel('Down payment', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(unit).toHaveValue('percent')
  await expect(page.getByLabel('Upfront purchase charges', { exact: true })).toHaveValue('7')
  await expect(page.getByLabel('Down payment', { exact: true })).toHaveValue('55')
})

test('waiting and rent-only both use computed mortgage-rent savings and additional starting charges', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/india')
  await page.getByLabel('Include waiting period', { exact: true }).check()
  await page.getByLabel('Home price', { exact: true }).fill('0.0036')
  await page.getByLabel('Down payment', { exact: true }).fill('0')
  await page.getByLabel('Upfront purchase charges unit', { exact: true }).selectOption('rupees')
  await page.getByLabel('Upfront purchase charges', { exact: true }).fill('1000')
  await page.getByLabel('Loan interest', { exact: true }).fill('0')
  await page.getByLabel('Loan term', { exact: true }).fill('3')
  await page.getByLabel('Comparable rent', { exact: true }).fill('500')
  await page.getByLabel('Annual rent increase', { exact: true }).fill('10')
  await page.getByLabel('Waiting period', { exact: true }).fill('1.5')
  await expect(page.locator('.compact-mortgage')).toContainText('Monthly mortgage payment₹1,000')
  await expect(page.locator('.compact-mortgage')).toContainText('Computed monthly savings₹500')
  await expect(page.locator('.compact-rent-only')).toContainText('Starting investment: ₹1,000')
  await expect(page.locator('.compact-rent-only')).toContainText('Mortgage–rent difference invested₹8,700')
  await expect(page.locator('.compact-rent-only')).toContainText('Ending investment balance₹9,700')
  await page.getByText('How this was calculated', { exact: true }).click()
  await page.getByText('Savings contributions by year', { exact: true }).click()
  const periods = page.getByRole('region', { name: 'Savings contributions by year' })
  await expect(periods.locator('tbody tr').last()).toContainText('₹1,000 mortgage − ₹550 rent')
  await expect(periods.locator('tfoot')).toContainText('₹8,700')
  const calculation = page.getByRole('region', { name: 'Detailed waiting calculation' })
  await expect(calculation.getByRole('row').filter({ has: page.getByRole('rowheader', { name: 'Available purchase cash', exact: true }) }).locator('td').last()).toHaveText('₹9,700')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'artifacts/computed-mortgage-mobile.png', fullPage: true })
})
