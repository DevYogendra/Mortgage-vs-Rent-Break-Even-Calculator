import { test, expect } from '@playwright/test'

test('savings amount and share stay in sync and translate the monthly plan to full calculations', async ({ page }) => {
  await page.goto('/india?goal=wait')
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  const amount = page.getByLabel('Monthly savings after rent and bills', { exact: true })
  const share = page.getByLabel('Share of take-home income saved', { exact: true })
  await page.getByLabel('Monthly take-home income in lakh', { exact: true }).fill('2')
  await expect(share).toHaveValue('31.25')
  await expect(page.locator('.beginner-savings-summary')).toContainText('₹62,500/month = 31.25%')
  await share.fill('20')
  await expect(amount).toHaveValue('40000')
  await amount.fill('62500')
  await expect(share).toHaveValue('31.25')
  await share.fill('101')
  await expect(share).toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByRole('button', { name: 'Continue', exact: true })).toBeDisabled()
  await share.fill('31.25')
  await page.screenshot({ path: 'artifacts/savings-share-desktop.png', fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.locator('.beginner-savings').screenshot({ path: 'artifacts/savings-share-mobile.png', animations: 'disabled' })
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.locator('.beginner-answer')).toContainText('₹37.5 lakh')
  await page.getByText('How this was calculated', { exact: true }).click()
  const calculations = page.getByRole('region', { name: 'Detailed waiting calculation', exact: true }).first()
  await expect(calculations.getByRole('row', { name: /^Starting monthly savings / })).toContainText('₹2,00,000 monthly take-home income × 31.25%')
  await expect(calculations.getByRole('row', { name: /^New savings from income / })).toContainText('₹62,500 per month × 60 months')
  await page.getByRole('button', { name: 'Full calculator', exact: true }).click()
  await expect(page.getByLabel('Annual savings share of income', { exact: true })).toHaveValue('31.25')
})

test('the visible annual return compounds to exactly one year and preserves contribution totals', async ({ page }) => {
  await page.goto('/india?goal=wait')
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await page.getByLabel('Monthly savings after rent and bills', { exact: true }).fill('0')
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  const annualReturn = page.getByLabel('Annual return on savings', { exact: true })
  await expect(annualReturn).toBeVisible()
  await annualReturn.fill('12')
  await page.getByLabel('Years you might wait', { exact: true }).fill('1')
  // ₹50 lakh starting purchase funds, 12% effective annual return, no new savings.
  await expect(page.locator('.beginner-answer')).toContainText('Investment returns add ₹6 lakh')
  await page.getByText('How this was calculated', { exact: true }).click()
  const calculations = page.getByRole('region', { name: 'Detailed waiting calculation', exact: true }).first()
  await expect(calculations.getByRole('row', { name: /^Available purchase cash / })).toContainText('₹56,00,000')
  await expect(page.locator('.beginner-results > .beginner-disclosure').first()).toContainText('12% per year')
  await expect(page.locator('.beginner-results > .delay-bar-section')).toContainText('₹0')
  await annualReturn.fill('')
  await expect(annualReturn).toHaveAttribute('aria-invalid', 'true')
  await expect(page.locator('.beginner-answer')).toHaveCount(0)
  await annualReturn.fill('0')
  await expect(page.locator('.beginner-answer')).toBeVisible()
  await page.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'What can your household put towards it?', exact: true })).toBeFocused()
  await expect(page.getByLabel('Share of take-home income saved', { exact: true })).toHaveValue('0')
  await page.getByLabel('Monthly take-home income in lakh', { exact: true }).fill('0')
  await expect(page.getByLabel('Monthly take-home income in lakh', { exact: true })).toHaveValue('0')
  await expect(page.getByLabel('Share of take-home income saved', { exact: true })).toBeDisabled()
  await expect(page.locator('.beginner-savings-summary')).toContainText('new savings from income are ₹0')
})

for (const goal of ['afford', 'wait']) {
  test(`step three shows the ${goal} answer immediately on desktop and mobile`, async ({ page }) => {
    for (const viewport of [{ width: 1440, height: 900 }, { width: 390, height: 844 }, { width: 320, height: 700 }]) {
      await page.setViewportSize(viewport)
      await page.emulateMedia({ reducedMotion: 'reduce' })
      await page.goto(`/india?goal=${goal}`)
      await page.getByRole('button', { name: 'Continue', exact: true }).click()
      await page.getByRole('button', { name: goal === 'afford' ? 'See my result' : 'Continue', exact: true }).click()
      const answer = page.getByRole('region', { name: 'Your answer', exact: true })
      await expect(answer.getByRole('heading')).toBeFocused()
      await expect(answer.getByRole('heading')).toBeInViewport({ ratio: 1 })
      await expect(answer.locator('.india-metric dd').first()).toBeInViewport({ ratio: 1 })
      await expect(answer.locator('.eyebrow')).toBeInViewport({ ratio: 1 })
      if (goal === 'wait') {
        await expect(answer.locator('p').nth(1)).toBeInViewport({ ratio: 1 })
        await page.getByLabel('Years you might wait').fill('3')
        await page.getByRole('button', { name: 'View updated result', exact: true }).click()
        await expect(answer.getByRole('heading')).toBeFocused()
        await expect(answer.getByRole('heading')).toBeInViewport({ ratio: 1 })
        await expect(answer.locator('.eyebrow')).toBeInViewport({ ratio: 1 })
        await expect(answer).toContainText('₹22.5 lakh')
      }
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await page.screenshot({ path: `artifacts/beginner-result-${goal}-${viewport.width}.png`, animations: 'disabled' })
    }
  })
}

