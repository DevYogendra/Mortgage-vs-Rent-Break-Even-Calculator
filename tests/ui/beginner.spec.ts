import { test, expect } from '@playwright/test'

test('beginners get focused steps, familiar units and the same affordability result', async ({ page }) => {
  await page.goto('/india')
  await expect(page.getByRole('button', { name: 'Beginner view', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByLabel('Home price in crore')).toHaveValue('1.5')
  await expect(page.getByLabel('Home price in crore').locator('..')).toContainText('₹ Cr')
  await expect(page.getByLabel('Monthly take-home income')).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Your answer', exact: true })).toHaveCount(0)
  await expect(page.getByText('Advanced settings', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Home-loan interest rate', { exact: true })).toBeHidden()
  await page.getByLabel('Home price in crore').fill('1.6')
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'What can your household put towards it?' })).toBeFocused()
  await expect(page.getByLabel('Monthly take-home income')).toHaveValue('250000')
  await expect(page.getByLabel('Savings available in lakh')).toHaveValue('55')
  await expect(page.getByLabel('Money to keep untouched in lakh')).toHaveValue('5')
  await page.getByLabel('Monthly savings after rent and bills').fill('50000')
  await page.getByRole('button', { name: 'See my result' }).click()
  const answer = page.getByRole('region', { name: 'Your answer', exact: true })
  await expect(answer).toContainText('This home is beyond your modeled budget.')
  const payment = await answer.locator('.india-metric dd').first().innerText()
  await page.getByRole('button', { name: 'Full calculator', exact: true }).click()
  await expect(page.getByLabel('Property price', { exact: true })).toHaveValue('1.6')
  await expect(page.getByLabel('Annual after-tax income', { exact: true })).toHaveValue('3000000')
  await expect(page.getByLabel('Annual savings share of income', { exact: true })).toHaveValue('20')
  const fullPayment = page.locator('.india-metric').filter({ has: page.getByText('Required monthly EMI', { exact: true }) }).locator('dd')
  await expect(fullPayment).toHaveText(payment)
  await page.getByRole('button', { name: 'Beginner view', exact: true }).click()
  await expect(page.getByLabel('Home price in crore')).toHaveValue('1.6')
  await page.getByRole('button', { name: 'Reset examples' }).click()
  await expect(page.getByLabel('Home price in crore')).toHaveValue('1.5')
  await page.reload()
  await expect(page.getByRole('button', { name: 'Beginner view', exact: true })).toHaveAttribute('aria-pressed', 'true')
})

