  await expect(page.locator('.india-pool-help')).toContainText('not forecasts of sales')
  await page.getByRole('link', { name: 'What happens if I wait?', exact: true }).click()
  await expect(page).toHaveURL(/\/india\?goal=wait$/)
  await page.reload()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
