test('goal navigation, keyboard operation and beginner layouts work in both themes on mobile', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/india')
  await page.getByRole('button', { name: 'What happens if I wait?', exact: true }).click()
  await page.getByRole('button', { name: 'Continue', exact: true }).focus()
  await page.keyboard.press('Enter')
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByLabel('Years you might wait')).toHaveValue('5')
  for (const theme of ['light', 'dark']) {
    await page.getByRole('combobox', { name: 'Color theme' }).selectOption(theme)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `artifacts/beginner-${theme}-mobile.png`, fullPage: true, animations: 'disabled' })
  }
  await page.setViewportSize({ width: 1440, height: 1050 })
  await page.screenshot({ path: 'artifacts/beginner-dark-desktop.png', fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 320, height: 700 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.getByText('Explore further: timeline, buyer tiers & full results', { exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('link', { name: 'How many households can buy?', exact: true }).click()
  await expect(page).toHaveURL(/\/india\/market$/)
  await expect(page.locator('.india-pool-help')).toContainText('not forecasts of sales')
  await page.getByRole('link', { name: 'What happens if I wait?', exact: true }).click()
  await expect(page).toHaveURL(/\/india\?goal=wait$/)
  await page.reload()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page.getByLabel('Years you might wait')).toHaveValue('5')
  expect(errors).toEqual([])
})
