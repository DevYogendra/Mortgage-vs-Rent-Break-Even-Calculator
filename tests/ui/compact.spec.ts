  await unit.selectOption('percent')
  await expect(savings).toHaveValue('31.25')
  await field(page, 'Take-home income').fill('3')
  await expect(savings).toHaveValue('31.25')
  await expect(page.locator('.compact-savings-summary')).toContainText('₹93,750/month')
