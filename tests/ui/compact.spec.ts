import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'

const field = (page: Page, name: string) => page.getByLabel(name, { exact: true })
const disclose = (page: Page, name: string) => page.getByText(name, { exact: true }).click()
const calculation = (page: Page, name: string) => page.getByRole('region', { name: 'Detailed waiting calculation', exact: true }).getByRole('row').filter({ has: page.getByRole('rowheader', { name, exact: true }) })
const comparison = (page: Page, name: string) => page.locator('.compact-comparison').getByRole('row').filter({ has: page.getByRole('rowheader', { name, exact: true }) })

test('all financial inputs are visible and results update immediately without moving focus or scrolling', async ({ page }) => {
  await page.goto('/india')
  await page.getByLabel('Include waiting period', { exact: true }).check()
  await expect(page.locator('form.compact-inputs > .compact-input-grid input[type=number]')).toHaveCount(12)
  await expect(page.getByLabel('Protected reserve', { exact: true })).toHaveCount(0)
  for (const input of await page.locator('form.compact-inputs > .compact-input-grid input').all()) await expect(input).toBeVisible()
  await expect(field(page, 'Home price')).toHaveValue('1.5')
  await expect(field(page, 'Take-home income')).toHaveValue('2.5')
  await expect(field(page, 'Income growth')).toHaveCount(0)
  await expect(field(page, 'Down payment')).toHaveValue('55')
  await expect(comparison(page, 'Available purchase cash').locator('td').first()).toHaveText('₹65,50,000')
  await expect(field(page, 'Waiting period')).toHaveValue('5')
  await expect(comparison(page, 'Purchase funding')).toContainText('Cash + loan share fit')
  await expect(page.locator('.compact-waiting')).toContainText('₹29.56 lakh')
  await expect(page.locator('.compact-waiting')).toContainText('₹34.77 lakh')
  await expect(page.locator('.compact-waiting')).toContainText('−₹5.22 lakh')
  await field(page, 'House-price growth').fill('10')
  await field(page, 'Waiting period').fill('3')
  await expect(page.locator('.compact-waiting')).toContainText('−₹35.04 lakh')
  await expect(page.locator('.compact-waiting')).toContainText('Further from covering the purchase')
  await field(page, 'Home price').focus()
  const scroll = await page.evaluate(() => scrollY)
  await field(page, 'Home price').fill('1.6')
  await expect(field(page, 'Home price')).toBeFocused()
  expect(await page.evaluate(() => scrollY)).toBe(scroll)
  await expect(page.getByRole('button', { name: /Continue|Back|Full calculator|Calculate/ })).toHaveCount(0)
  await expect(page.getByRole('group', { name: 'Savings and house price timeline', exact: true })).toBeHidden()
  await expect(page.getByRole('region', { name: 'Detailed waiting calculation', exact: true })).toBeHidden()
})

test('reset and reload restore five years and other defaults; old goal links still work', async ({ page }) => {
  await page.goto('/india?goal=afford')
  await page.getByLabel('Include waiting period', { exact: true }).check()
  await field(page, 'Home price').fill('1.8')
  await field(page, 'Waiting period').fill('2')
  await field(page, 'Annual rent increase').fill('10')
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await page.getByLabel('Include waiting period', { exact: true }).check()
  await expect(field(page, 'Home price')).toHaveValue('1.5')
  await expect(field(page, 'Waiting period')).toHaveValue('5')
  await expect(field(page, 'Savings')).toHaveCount(0)
  await field(page, 'Waiting period').fill('3')
  await page.reload()
  await page.getByLabel('Include waiting period', { exact: true }).check()
  await expect(field(page, 'Waiting period')).toHaveValue('5')
  await page.getByRole('navigation').getByRole('link', { name: 'Price vs buyer capacity' }).click()
  await page.getByRole('link', { name: 'What happens if I wait?', exact: true }).click()
  await expect(page).toHaveURL(/\/india\?goal=wait$/)
  await expect(field(page, 'Waiting period')).toHaveValue('5')
})

