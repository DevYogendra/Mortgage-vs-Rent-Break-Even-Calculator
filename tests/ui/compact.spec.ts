test('falling prices, zero savings and zero wait stay finite; tables scroll on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/india')
  await page.getByLabel('Include waiting period', { exact: true }).check()
  await field(page, 'Comparable rent').fill('200000')
  await field(page, 'House-price growth').fill('-10')
  await field(page, 'Investment return').fill('-5')
  await expect(page.locator('.delay-bar-row').first()).toContainText('₹0')
  const negativeBar = page.locator('.delay-bar-row').last()
  await expect(negativeBar).toContainText('-₹61,42,650')
  const bar = await negativeBar.locator('.delay-bar-fill').boundingBox(), zero = await negativeBar.locator('.delay-bar-zero').boundingBox()
  expect(bar!.x + bar!.width).toBeLessThanOrEqual(zero!.x + zero!.width + 1)
  await disclose(page, 'How this was calculated')
  const table = page.getByRole('region', { name: 'Detailed waiting calculation' })
  await table.focus(); await table.press('ArrowRight')
  await expect.poll(() => table.evaluate(el => el.scrollLeft)).toBeGreaterThan(0)
  await field(page, 'Waiting period').fill('0')
  await expect(page.locator('.compact-waiting')).toContainText('Buying today')
  await expect(page.locator('.compact-waiting')).not.toContainText('NaN')
  await expect(page.locator('.compact-waiting')).not.toContainText('Infinity')
  await expect(page.getByRole('slider', { name: 'Inspect month' })).toHaveValue('0')
})

