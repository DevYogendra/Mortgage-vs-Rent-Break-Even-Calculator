import { test, expect } from '@playwright/test'

test('waiting opt-in reveals income fields and invests 90% of anniversary income increases', async ({ page }) => {
  await page.goto('/india')
  await expect(page.getByLabel('Include waiting period', { exact: true })).not.toBeChecked()
  await expect(page.getByLabel('Take-home income', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Annual increment', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Maximum financed share', { exact: true })).toHaveCount(0)
  await expect(page.locator('.compact-waiting')).toHaveCount(0)
  await page.getByLabel('Home price', { exact: true }).fill('0.0036')
  await page.getByLabel('Down payment', { exact: true }).fill('0')
  await page.getByLabel('Upfront purchase charges', { exact: true }).fill('0')
  await page.getByLabel('Loan interest', { exact: true }).fill('0')
  await page.getByLabel('Loan term', { exact: true }).fill('3')
  await page.getByLabel('Comparable rent', { exact: true }).fill('500')
  await page.getByLabel('Annual rent increase', { exact: true }).fill('10')
  await page.getByLabel('Rental period', { exact: true }).fill('1.5')
  await expect(page.locator('.compact-rent-only')).toContainText('Ending investment balance₹8,700')
  await page.getByLabel('Include waiting period', { exact: true }).check()
  await page.getByLabel('Take-home income', { exact: true }).fill('0.01')
  await page.getByLabel('Annual increment', { exact: true }).fill('10')
  await expect(page.locator('.compact-waiting')).toContainText('Projected monthly take-home: ₹1,100')
  await page.getByText('How this was calculated', { exact: true }).click()
  await page.getByText('Savings contributions by year', { exact: true }).click()
  const table = page.getByRole('region', { name: 'Detailed waiting calculation' })
  await expect(table.getByRole('row').filter({ has: page.getByRole('rowheader', { name: 'Total savings invested', exact: true }) }).locator('td').last()).toHaveText('₹9,240')
  const periods = page.getByRole('region', { name: 'Savings contributions by year' })
  await expect(periods.locator('tbody tr').last()).toContainText('₹90 income savings × 6 months')
  await expect(periods.locator('tfoot')).toContainText('₹9,240')
  await expect(page.locator('.compact-rent-only')).toContainText('Ending investment balance₹8,700')
  await page.getByLabel('Annual increment', { exact: true }).fill('-1')
  await expect(page.getByLabel('Annual increment', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await expect(page.locator('.compact-rent-only')).toBeVisible()
  await page.getByLabel('Include waiting period', { exact: true }).uncheck()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(page.getByLabel('Annual increment', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Take-home income', { exact: true })).toHaveCount(0)
  await expect(page.locator('.compact-waiting')).toHaveCount(0)
  await expect(page.locator('.compact-rent-only')).toContainText('Ending investment balance₹8,700')
})

test('minimum take-home uses 20% down, the EMI limit and the 4x annual-income mortgage cap', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 900 })
  await page.goto('/india')
  await page.getByLabel('Home price', { exact: true }).fill('1.5')
  await page.getByLabel('Loan interest', { exact: true }).fill('0')
  await page.getByLabel('Loan term', { exact: true }).fill('20')
  const minimum = page.getByLabel('Minimum take-home needed', { exact: true })
  // 80% of ₹1.5 crore = ₹1.2 crore. Its 4x income cap requires ₹2.5 lakh/month.
  await expect(minimum).toHaveValue('₹2,50,000')
  await expect(minimum).toHaveAttribute('readonly', '')
  await page.getByLabel('Down payment', { exact: true }).fill('40')
  await expect(minimum).toHaveValue('₹2,50,000')
  await page.getByLabel('Loan term', { exact: true }).fill('5')
  // EMI ₹2 lakh at zero interest / 40% = ₹5 lakh/month, now the tighter limit.
  await expect(minimum).toHaveValue('₹5,00,000')
  await page.getByLabel('Include waiting period', { exact: true }).check()
  await page.getByLabel('Annual increment', { exact: true }).fill('10')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'artifacts/waiting-income-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(page.getByLabel('Include waiting period', { exact: true })).not.toBeChecked()
  await expect(page.getByLabel('Take-home income', { exact: true })).toHaveCount(0)
})
