import { readFile } from 'node:fs/promises'
import { test, expect } from '@playwright/test'
import { defaults, simulate } from '../../src/engine'
import { createCalculationReport, monthlyCsv } from '../../src/report'

// Browser and Node math implementations can differ by a last bit in log/expm1.
// Serialization itself is tested for exact round trips in report.test.ts.
function expectReport(actual: unknown, expected: unknown) {
  if (typeof expected === 'number') {
    expect(typeof actual).toBe('number')
    expect(actual as number).toBeCloseTo(expected, 8)
  } else if (Array.isArray(expected)) {
    expect(Array.isArray(actual)).toBe(true)
    expect((actual as unknown[]).length).toBe(expected.length)
    expected.forEach((value, i) => expectReport((actual as unknown[])[i], value))
  } else if (expected !== null && typeof expected === 'object') {
    expect(actual).not.toBeNull()
    expect(Object.keys(actual as object).sort()).toEqual(Object.keys(expected).sort())
    for (const [key, value] of Object.entries(expected)) expectReport((actual as Record<string, unknown>)[key], value)
  } else {
    expect(actual).toEqual(expected)
  }
}

test('opens and inspects the report, exports all months, and keeps a calculated snapshot', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  const report = page.locator('#calculation-report')
  await expect(report).not.toHaveAttribute('open')
  await page.getByRole('link', { name: 'Show calculations' }).click()
  await expect(report).toHaveAttribute('open', '')
  await expect.poll(() => report.evaluate(el => Math.abs(el.getBoundingClientRect().top - 24))).toBeLessThan(2)
  await expect(report.locator('summary')).toBeFocused()
  await expect(report.getByRole('heading', { name: 'Capital, mortgage & compounding' })).toBeVisible()
  await expect(report.getByRole('heading', { name: 'Month 1 calculations' })).toBeVisible()
  await expect(page.getByLabel('Ledger year')).toHaveValue('1')
  await expect(page.locator('.monthly-ledger tbody tr')).toHaveCount(12)
  await expect(report.locator('.report-portfolio').first()).toContainText('Gain / loss on down payment')
  await expect(report.locator('.report-portfolio').first()).toContainText('Gain / loss on closing costs')
  await expect(report.locator('.formula-working').first()).toContainText('$480,000.00')
  await page.getByLabel('Ledger year').selectOption('2')
  await expect(page.getByRole('heading', { name: 'Month 13 calculations' })).toBeVisible()
  await page.getByRole('button', { name: 'Inspect month 14' }).focus()
  await page.getByRole('button', { name: 'Inspect month 14' }).press('Enter')
  await expect(page.getByRole('heading', { name: 'Month 14 calculations' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Inspect month 14' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('tab', { name: 'Mortgage', exact: true }).focus()
  await page.getByRole('tab', { name: 'Mortgage', exact: true }).press('ArrowRight')
  await expect(page.getByRole('tab', { name: 'Housing costs', exact: true })).toBeFocused()
  await expect(page.locator('.monthly-ledger')).toContainText('Renters insurance')
  await page.getByRole('tab', { name: 'Housing costs', exact: true }).press('End')
  await expect(page.getByRole('tab', { name: 'Investments', exact: true })).toBeFocused()
  await expect(page.locator('.monthly-ledger')).toContainText('Renter gain / loss')
  const [csvDownload] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Download monthly CSV' }).click()])
  const csv = await readFile((await csvDownload.path())!, 'utf8')
  expect(csvDownload.suggestedFilename()).toBe('home-rent-monthly.csv')
  expect(csv).toBe(monthlyCsv(createCalculationReport(simulate(defaults))))
  expect(csv.trimEnd().split('\r\n')).toHaveLength(121)
  await page.getByLabel('Purchase price', { exact: true }).fill('650000')
  await expect(report.locator('.report-stale')).toContainText('last calculated assumptions')
  const [oldDownload] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Download calculation JSON' }).click()])
  const oldJson = JSON.parse(await readFile((await oldDownload.path())!, 'utf8'))
  expectReport(oldJson, createCalculationReport(simulate(defaults)))
  await page.getByRole('button', { name: 'Calculate break-even' }).click()
  await expect(report).toHaveAttribute('open', '')
  await expect(report.locator('.report-stale')).toHaveCount(0)
  await expect(page.getByLabel('Ledger year')).toHaveValue('1')
  await expect(page.getByRole('heading', { name: 'Month 1 calculations' })).toBeVisible()
  const [newDownload] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Download calculation JSON' }).click()])
  const newJson = JSON.parse(await readFile((await newDownload.path())!, 'utf8'))
  expect(newDownload.suggestedFilename()).toBe('home-rent-calculation.json')
  expectReport(newJson, createCalculationReport(simulate({ ...defaults, price: 650000 })))
  await page.setViewportSize({ width: 1440, height: 1050 })
  await page.getByRole('link', { name: 'Show calculations' }).click()
  await expect.poll(() => report.evaluate(el => Math.abs(el.getBoundingClientRect().top - 24))).toBeLessThan(2)
  await page.screenshot({ path: 'artifacts/report-desktop.png' })
  expect(errors).toEqual([])
})

test('mobile report handles partial years, negative returns and a zero sale-price boundary', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  await page.getByLabel('Down payment', { exact: true }).fill('100')
  await page.getByLabel('Years in the home', { exact: true }).fill('1.5')
  await page.getByRole('button', { name: '03 Rent' }).click()
  await page.getByLabel('Current monthly rent', { exact: true }).fill('50000')
  await page.getByRole('button', { name: /04 Investment/ }).click()
  await page.getByLabel('Annual investment return', { exact: true }).fill('-10')
  await page.getByRole('button', { name: 'Calculate break-even' }).click()
  await page.getByRole('link', { name: 'Show calculations' }).click()
  const report = page.locator('#calculation-report')
  await expect(report.getByRole('heading', { name: 'No appreciation threshold' })).toBeVisible()
  await expect(report.getByRole('heading', { name: 'Required annual appreciation' })).toHaveCount(0)
  await expect(report).toContainText('it does not claim a positive break-even sale')
  await expect(report.locator('.report-portfolio').first()).toContainText('-$')
  await page.getByLabel('Ledger year').selectOption('2')
  await expect(page.locator('.monthly-ledger tbody tr')).toHaveCount(6)
  await page.getByRole('button', { name: 'Inspect month 18' }).click()
  await expect(page.getByRole('heading', { name: 'Month 18 calculations' })).toBeVisible()
  await expect(report).toContainText('Cash purchase: $0.00 monthly P&I')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Download calculation JSON' }).click()])
  const json = JSON.parse(await readFile((await download.path())!, 'utf8'))
  expect(json.months).toHaveLength(18)
  expect(json.annual.at(-1).months).toBe(6)
  expect(json.inputs.investmentReturn).toBe(-.1)
  expect(json.result.status).toBe('buy-always')
  await page.getByRole('link', { name: 'Show calculations' }).click()
  await expect.poll(() => report.evaluate(el => Math.abs(el.getBoundingClientRect().top - 24))).toBeLessThan(2)
  await page.screenshot({ path: 'artifacts/report-mobile.png' })
})
