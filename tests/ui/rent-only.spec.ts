import { test, expect } from '@playwright/test'

test('rent-only compounds annual rent and invests only mortgage minus rent', async ({ page }) => {
  await page.goto('/india')
  await page.getByLabel('Home price', { exact: true }).fill('0.0036')
  await page.getByLabel('Upfront purchase charges', { exact: true }).fill('0')
  await page.getByLabel('Liquid purchase funds', { exact: true }).fill('0')
  await page.getByLabel('Loan interest', { exact: true }).fill('0')
  await page.getByLabel('Loan term', { exact: true }).fill('3')
  await page.getByLabel('Comparable rent', { exact: true }).fill('500')
  await page.getByLabel('Annual rent increase', { exact: true }).fill('10')
  await page.getByLabel('Waiting period', { exact: true }).fill('1.5')
  const summary = page.locator('.compact-rent-only')
  await expect(summary).toContainText('Total rent paid₹9,300')
  await expect(summary).toContainText('Mortgage–rent difference invested₹8,700')
  await expect(summary).toContainText('Ending investment balance₹8,700')
  await page.getByText('Rent-only year-by-year calculation', { exact: true }).click()
  const table = page.getByRole('region', { name: 'Rent-only annual projection' })
  await expect(table.locator('tbody tr')).toHaveCount(2)
  await expect(table.locator('tbody tr').last()).toContainText('10%')
  await expect(table.locator('tbody tr').last()).toContainText('₹550')
  await expect(table.locator('tbody tr').last().locator('td').first()).toHaveText('6')
  // Income savings belong to waiting to buy, and must never fund rent-only investments.
  await page.getByLabel('Savings', { exact: true }).fill('100000')
  await expect(page.getByLabel('Income growth', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Take-home income', { exact: true })).toHaveCount(0)
  await expect(summary).toContainText('Ending investment balance₹8,700')
  await page.getByLabel('Savings return', { exact: true }).fill('12')
  await expect(summary).not.toContainText('Ending investment balance₹8,700')
  await page.getByLabel('Comparable rent', { exact: true }).fill('1500')
  await expect(summary).toContainText('Ending investment balance₹0')
  await page.getByLabel('Annual rent increase', { exact: true }).fill('-100')
  await expect(page.getByLabel('Annual rent increase', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByRole('alert')).toContainText('Rent-only results are withheld')
  await expect(summary).toHaveCount(0)
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(page.getByLabel('Annual rent increase', { exact: true })).toHaveValue('3')
  await expect(summary).toBeVisible()
})

