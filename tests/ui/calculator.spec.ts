import { test, expect } from '@playwright/test'
test('calculate, validation, units and scenario interactions', async ({ page }) => {
  const runtimeErrors: string[] = []
  page.on('pageerror', error => runtimeErrors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Rent or buy? Run the numbers.' })).toBeVisible()
  await expect(page.locator('.big-result')).toContainText('%')
  const old = await page.locator('.big-result').innerText()
  await page.getByLabel('Purchase price', { exact: true }).fill('650000')
  await expect(page.getByRole('status')).toContainText('Assumptions changed')
  await page.getByRole('button', { name: 'Calculate break-even' }).click()
  await expect(page.locator('.result-assumptions')).toContainText('$650,000')
  expect(await page.locator('.big-result').innerText()).not.toBe(old)
  await expect(page.locator('.reconciliation')).toContainText('$0.00')
  await page.getByLabel('Down payment unit').selectOption('dollars')
  await expect(page.getByLabel('Down payment', { exact: true })).toHaveValue('130000')
  await page.getByLabel('Purchase price', { exact: true }).fill('0')
  await page.getByRole('button', { name: 'Calculate break-even' }).click()
  await expect(page.getByRole('alert')).toContainText('Purchase price')
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await page.getByRole('tab', { name: 'Try appreciation' }).click()
  await expect(page.locator('.scenario-answer')).toContainText('the strategies break even')
  await page.getByRole('button', { name: '0%', exact: true }).click()
  await expect(page.locator('.scenario-answer')).toContainText('renting finishes')
  await page.getByLabel('Home appreciation', { exact: true }).fill('100')
  await expect(page.locator('.scenario-answer')).toContainText('buying finishes')
  await page.getByLabel('Home appreciation', { exact: true }).fill('-100')
  await expect(page.getByRole('alert')).toContainText('greater than')
  await page.getByRole('tab', { name: 'Sensitivity', exact: true }).click()
  await expect(page.locator('.sensitivity-table tbody tr')).toHaveCount(8)
  await page.getByRole('tab', { name: 'Sensitivity', exact: true }).press('ArrowRight')
  await expect(page.getByRole('tab', { name: 'Holding period' })).toBeFocused()
  await expect(page.locator('.annual-table tbody tr')).toHaveCount(10)
  await page.getByText('Full calculation breakdown', { exact: false }).click()
  await expect(page.getByText('Total interest paid', { exact: true })).toBeVisible()
  expect(runtimeErrors).toEqual([])
  await page.setViewportSize({ width: 1440, height: 1050 })
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await page.screenshot({ path: 'artifacts/desktop.png', fullPage: true })
})
test('mobile fits and inputs recalculate', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: '03 Rent' }).click()
  await page.getByLabel('Current monthly rent', { exact: true }).fill('3200')
  await page.getByRole('button', { name: 'Calculate break-even' }).click()
  await expect(page.locator('.cash-columns')).toContainText('$3,220')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'artifacts/mobile.png', fullPage: true })
})
test('cash purchase, partial years and no positive threshold', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Down payment', { exact: true }).fill('100')
  await page.getByLabel('Years in the home', { exact: true }).fill('1.5')
  await page.getByRole('button', { name: '03 Rent' }).click()
  await page.getByLabel('Current monthly rent', { exact: true }).fill('50000')
  await page.getByRole('button', { name: 'Calculate break-even' }).click()
  await expect(page.locator('.no-threshold')).toContainText('Buying is already ahead')
  await expect(page.locator('.annual-table tbody tr')).toHaveCount(2)
  await expect(page.locator('.annual-table tbody tr').last()).toContainText('6 months')
  await page.getByRole('tab', { name: 'Try appreciation' }).click()
  await expect(page.locator('.scenario-answer')).toContainText('buying finishes')
})
