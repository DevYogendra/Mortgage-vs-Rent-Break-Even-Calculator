import { test, expect } from '@playwright/test'

test('full-loan rental row projects net worth even when the selected rental period is zero', async ({ page }) => {
  await page.goto('/india')
  await page.getByLabel('Home price', { exact: true }).fill('0.0036')
  await page.getByLabel('Down payment', { exact: true }).fill('0')
  await page.getByLabel('Upfront purchase charges unit', { exact: true }).selectOption('rupees')
  await page.getByLabel('Upfront purchase charges', { exact: true }).fill('1000')
  await page.getByLabel('Loan interest', { exact: true }).fill('0')
  await page.getByLabel('Loan term', { exact: true }).fill('3')
  await page.getByLabel('Comparable rent', { exact: true }).fill('500')
  await page.getByLabel('Annual rent increase', { exact: true }).fill('10')
  await page.getByLabel('Rental period', { exact: true }).fill('0')
  const full = page.locator('.compact-loan-term-rental')
  await expect(page.locator('.compact-rent-only')).toContainText('Keep renting for 0 years')
  await expect(full).toContainText('Keep renting for the full loan term (3 years)')
  await expect(full).toContainText('Total rent paid₹19,860')
  await expect(full).toContainText('Mortgage–rent difference invested₹16,140')
  await expect(full).toContainText('Total investment net worth₹17,140')
  const original = await full.innerText()
  await page.getByLabel('Rental period', { exact: true }).fill('1.5')
  expect(await full.innerText()).toBe(original)
  await page.getByLabel('Include waiting period', { exact: true }).check()
  await page.getByLabel('Annual increment', { exact: true }).fill('10')
  expect(await full.innerText()).toBe(original)
  await page.getByText('Loan-term rent-only year-by-year calculation', { exact: true }).click()
  await expect(page.getByRole('region', { name: 'Loan-term rent-only annual projection' }).locator('tbody tr')).toHaveCount(3)
  await page.getByLabel('Loan term', { exact: true }).fill('2')
  await expect(full).toContainText('full loan term (2 years)')
  await page.getByLabel('Investment return', { exact: true }).fill('12')
  await expect(full).not.toContainText('Investment gain / loss: ₹0')
})

