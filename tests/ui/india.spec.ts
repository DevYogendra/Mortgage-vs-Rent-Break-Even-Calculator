test('purchase delay compares current and future prices, savings, EMIs and tiers', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/india')
  await expect(page.getByLabel('Years before purchase', { exact: true })).toHaveValue('0')
  await expect(page.locator('.india-delay')).toContainText('Set “Years before purchase”')
  await page.getByLabel('Annual property appreciation', { exact: true }).fill('10')
  await page.getByLabel('Years before purchase', { exact: true }).fill('3')
  await expect(page.locator('.india-result')).toContainText('Tier 2')
  await expect(page.locator('.india-delay-answer')).toContainText('After 3 years: Tier 3')
  const comparison = page.getByRole('region', { name: 'Buy now versus delayed purchase', exact: true })
  await expect(comparison.getByRole('row', { name: /^Property price / })).toContainText('₹1,99,65,000')
  await expect(comparison.getByRole('row', { name: /^Available purchase cash / })).toContainText('₹72,50,000')
  await expect(comparison.getByRole('row', { name: /^Required home loan / })).toContainText('₹1,41,12,550')
  await page.getByText('Year-by-year affordability', { exact: true }).click()
  const timeline = page.getByRole('region', { name: 'Purchase delay timeline', exact: true })
  await expect(timeline.locator('tbody tr')).toHaveCount(4)
  await page.getByLabel('Annual after-tax income growth', { exact: true }).fill('10')
  await expect(comparison.getByRole('row', { name: /^Annual after-tax income / })).toContainText('₹39,93,000')
  await expect(page.locator('.india-delay-answer')).toContainText('After 3 years: Tier 2')
  await page.getByLabel('Annual savings return', { exact: true }).fill('5')
  await expect(comparison.getByRole('row', { name: /^Available purchase cash / })).not.toContainText('₹74,82,500')
  await page.getByLabel('Years before purchase', { exact: true }).fill('3.5')
  await expect(timeline.locator('tbody tr')).toHaveCount(5)
  await expect(timeline.locator('tbody tr').last()).toContainText('3.5')
  await page.getByRole('button', { name: 'Reset examples' }).click()
  await expect(page.getByLabel('Years before purchase', { exact: true })).toHaveValue('0')
  await expect(page.getByLabel('Annual after-tax income growth', { exact: true })).toHaveValue('0')
  await expect(page.getByLabel('Annual savings return', { exact: true })).toHaveValue('0')
  await expect(page.locator('.india-delay-comparison')).toHaveCount(0)
  expect(errors).toEqual([])
})

