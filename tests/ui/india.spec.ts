import { test, expect } from '@playwright/test'

test('links all calculators, supports direct links, refresh and browser history', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('link', { name: 'India calculators' }).click()
  await expect(page).toHaveURL(/\/india$/)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Homebuyer capacity')
  await expect(page).toHaveTitle('Home / Rent — India Homebuyer capacity')
  const nav = page.getByRole('navigation', { name: 'India calculators' })
  await expect(nav.getByRole('link', { name: 'Homebuyer capacity' })).toHaveAttribute('aria-current', 'page')
  await nav.getByRole('link', { name: 'Price vs buyer capacity' }).click()
  await expect(page).toHaveURL(/\/india\/market$/)
  await page.reload()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Price vs buyer capacity')
  await nav.getByRole('link', { name: 'Builder / sales demand' }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Builder / sales demand')
  await page.goBack()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Price vs buyer capacity')
  await page.goForward()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Builder / sales demand')
  await page.getByRole('link', { name: 'US calculator' }).click()
  await expect(page.locator('.big-result')).toContainText('4.39%')
  expect(errors).toEqual([])
})

test('builder segments update counts and gates, and can be added, renamed and removed', async ({ page }) => {
  await page.goto('/india/builders')
  await expect(page.locator('.india-result h2')).toContainText('350')
  await expect(page.locator('.india-segment-results tbody tr')).toHaveCount(3)
  await page.getByLabel('Household count — Income-backed example', { exact: true }).fill('300')
  await expect(page.locator('.india-result h2')).toContainText('400')
  await page.getByText('Buying intentions for this segment', { exact: true }).click()
  await page.getByLabel('Willing to buy today — Income-backed example', { exact: true }).uncheck()
  await expect(page.locator('.india-result h2')).toContainText('100')
  await expect(page.locator('.india-pool-metrics')).toContainText('400')
  await page.getByRole('button', { name: 'Add segment' }).click()
  await expect(page.getByLabel('Household segment', { exact: true }).locator('option')).toHaveCount(4)
  await page.getByLabel('Segment name 4', { exact: true }).fill('New buyers')
  await page.getByLabel('Household count — New buyers', { exact: true }).fill('5')
  await expect(page.locator('.india-result h2')).toContainText('105')
  await expect(page.locator('.india-pool-metrics')).toContainText('405')
  await page.getByRole('button', { name: 'Remove New buyers', exact: true }).click()
  await expect(page.locator('.india-result h2')).toContainText('100')
  await page.getByRole('button', { name: 'Reset examples' }).click()
  await expect(page.getByLabel('Household segment', { exact: true }).locator('option')).toHaveCount(3)
  await expect(page.locator('.india-result h2')).toContainText('350')
})

test('invalid segment inputs clear dependent results and removing the row restores them', async ({ page }) => {
  await page.goto('/india/builders')
  await page.getByLabel('Household count — Income-backed example', { exact: true }).fill('1.5')
  await expect(page.getByRole('alert')).toContainText('whole number')
  await expect(page.locator('.india-result')).toHaveCount(0)
  await expect(page.locator('.india-segment-results')).toHaveCount(0)
  await page.getByLabel('Household count — Income-backed example', { exact: true }).fill('250')
  await page.getByLabel('Protected cash reserve — Income-backed example', { exact: true }).fill('60')
  await expect(page.getByRole('alert')).toContainText('cannot exceed')
  await page.getByRole('button', { name: 'Remove Income-backed example', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(page.locator('.india-result h2')).toContainText('100')
})

test('empty segments produce a zero pool without errors', async ({ page }) => {
  await page.goto('/india/builders')
  for (const name of ['Wealth-backed example', 'Income-backed example', 'Constrained example']) {
    await page.getByLabel('Household segment', { exact: true }).selectOption({ label: name })
    await page.getByRole('button', { name: `Remove ${name}`, exact: true }).click()
  }
  await expect(page.locator('.india-result h2')).toHaveText('0 households')
  await expect(page.locator('.india-results')).toContainText('No households are entered')
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.getByRole('button', { name: 'Add segment' }).click()
  await expect(page.locator('.india-result h2')).toHaveText('0 households')
})

test('market chart is keyboard accessible and reflects exact-price counts and demand gates', async ({ page }) => {
  await page.goto('/india/market')
  const chart = page.getByRole('group', { name: 'Household capacity by property price', exact: true })
  const points = chart.getByRole('button')
  await expect(points).toHaveCount(21)
  await points.nth(10).focus()
  await expect(points.nth(10)).toBeFocused()
  await points.nth(10).press('Enter')
  await expect(page.locator('.india-chart-caption')).toContainText('350 capable · 350 effective')
  await page.getByText('Edit household segments', { exact: true }).click()
  await page.getByText('Buying intentions for this segment', { exact: true }).click()
  await page.getByLabel('Willing to buy today — Income-backed example', { exact: true }).uncheck()
  await expect(page.locator('.india-result h2')).toContainText('100')
  await expect(page.locator('.india-chart-caption')).toContainText('350 capable · 100 effective')
  await page.getByLabel('Property price', { exact: true }).fill('1.5000001')
  await expect(points.nth(10)).toHaveAttribute('aria-label', '₹1,50,00,001: 350 capable, 100 effective households')
  await page.getByText('View all 21 chart prices', { exact: true }).click()
  await expect(page.getByRole('region', { name: 'Price capacity data', exact: true }).locator('tbody tr')).toHaveCount(21)
  await page.getByLabel('Property price', { exact: true }).fill('2')
  await expect(page.locator('.india-pool-metrics')).toContainText('100')
  await page.getByLabel('Property price', { exact: true }).fill('')
  await expect(page.getByRole('alert')).toContainText('Property price')
  await expect(chart).toHaveCount(0)
})

test('market and builder pages agree with the same edited scenarios', async ({ page }) => {
  const results: string[] = []
  for (const path of ['/india/market', '/india/builders']) {
    await page.goto(path)
    if (path.endsWith('market')) await page.getByText('Edit household segments', { exact: true }).click()
    await page.getByLabel('Property price', { exact: true }).fill('1.8')
    await page.getByLabel('Household segment', { exact: true }).selectOption({ label: 'Wealth-backed example' })
    await page.getByLabel('Household count — Wealth-backed example', { exact: true }).fill('123')
    await page.getByLabel('Household segment', { exact: true }).selectOption({ label: 'Income-backed example' })
    await page.getByText('Buying intentions for this segment', { exact: true }).click()
    await page.getByLabel('Access to credit — Income-backed example', { exact: true }).uncheck()
    results.push(await page.locator('.india-segment-results').innerText())
  }
  expect(results[0]).toBe(results[1])
})
