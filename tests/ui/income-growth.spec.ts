import { test, expect } from '@playwright/test'

test('separate income growth solves the future EMI limit without changing projections', async ({ page }) => {
  await page.goto('/india')
  await page.getByLabel('Home price', { exact: true }).fill('0.0036')
  await page.getByLabel('Liquid purchase funds', { exact: true }).fill('0')
  await page.getByLabel('Upfront purchase charges', { exact: true }).fill('0')
  await page.getByLabel('Loan interest', { exact: true }).fill('0')
  await page.getByLabel('Loan term', { exact: true }).fill('3')
  await page.getByLabel('House-price growth', { exact: true }).fill('0')
  await page.getByLabel('Savings', { exact: true }).fill('0')
  const rental = await page.locator('.compact-rent-only').innerText()
  const waiting = await page.locator('.compact-waiting').innerText()
  await page.getByText('Income growth needed per year', { exact: true }).click()
  const assessment = page.locator('.income-growth-assessment')
  await page.getByLabel('Current monthly income', { exact: true }).fill('0.01')
  await expect(assessment).toContainText('Projected monthly mortgage₹1,000')
  await expect(assessment).toContainText('Required monthly income₹2,500')
  await expect(assessment).toContainText('Required annual income growth20.11%')
  await page.getByLabel('Other monthly loan payments', { exact: true }).fill('1000')
  await expect(assessment).toContainText('Required monthly income₹5,000')
  await page.getByLabel('Loan-payment limit', { exact: true }).fill('50')
  await expect(assessment).toContainText('Required monthly income₹4,000')
  expect(await page.locator('.compact-rent-only').innerText()).toBe(rental)
  expect(await page.locator('.compact-waiting').innerText()).toBe(waiting)
  await page.getByLabel('Current monthly income', { exact: true }).fill('0')
  await expect(assessment).toContainText('cannot be computed from zero income')
  await page.getByLabel('Current monthly income', { exact: true }).fill('-1')
  await expect(assessment.getByRole('alert')).toBeVisible()
  await expect(page.locator('.compact-rent-only')).toBeVisible()
  await page.getByLabel('Current monthly income', { exact: true }).fill('0.01')
  await page.getByLabel('Waiting period', { exact: true }).fill('0')
  await expect(assessment).toContainText('there is no time to grow income')
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await expect(page.getByLabel('Current monthly income', { exact: true })).toHaveValue('2.5')
})

test('fixed monthly savings need no income input and partial-year totals stay constant', async ({ page }) => {
  await page.goto('/india')
  await expect(page.getByLabel('Take-home income', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Income growth', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Savings unit', { exact: true })).toHaveCount(0)
  await page.getByLabel('Waiting period', { exact: true }).fill('1.5')
  await page.getByText('How this was calculated', { exact: true }).click()
  await page.getByText('Savings contributions by year', { exact: true }).click()
  const periods = page.getByRole('region', { name: 'Savings contributions by year' })
  await expect(periods.locator('tbody tr').last()).toContainText('₹62,500 per month × 6 months')
  await expect(periods.locator('tfoot')).toContainText('₹11,25,000')
  await expect(periods).not.toContainText('Annual after-tax income')
  for (const invalid of ['-1', '']) {
    await page.getByLabel('Savings', { exact: true }).fill(invalid)
    await expect(page.getByLabel('Savings', { exact: true })).toHaveAttribute('aria-invalid', 'true')
    await expect(page.getByRole('alert')).toBeVisible()
    await expect(page.locator('.compact-waiting')).toHaveCount(0)
  }
  await page.getByLabel('Savings', { exact: true }).fill('62500')
  await expect(page.locator('.compact-waiting')).toBeVisible()
})

test('starting funds earn returns when there is no mortgage-rent surplus', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/india')
  await page.getByLabel('Liquid purchase funds', { exact: true }).fill('50')
  await page.getByLabel('Comparable rent', { exact: true }).fill('200000')
  await page.getByLabel('Savings return', { exact: true }).fill('12')
  await page.getByLabel('Waiting period', { exact: true }).fill('1')
  const rental = page.locator('.compact-rent-only')
  await expect(rental).toContainText('Starting investment: ₹50,00,000')
  await expect(rental).toContainText('Mortgage–rent difference invested₹0')
  await expect(rental).toContainText('Ending investment balance₹56,00,000')
  await expect(rental).toContainText('Investment gain / loss: ₹6,00,000')
  await page.getByText('Income growth needed per year', { exact: true }).click()
  await page.getByLabel('Current monthly income', { exact: true }).fill('100')
  await expect(rental).toContainText('Ending investment balance₹56,00,000')
  await page.getByText('Rent-only year-by-year calculation', { exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'artifacts/rent-only-starting-funds-mobile.png', fullPage: true })
})
